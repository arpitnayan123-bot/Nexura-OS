const clamp = (n: number, lo: number, hi: number) => Math.min(hi, Math.max(lo, n));
const r0 = (n: number) => Math.round(n);
const r1 = (n: number) => Math.round(n * 10) / 10;

/** deterministic pseudo-shuffle from a numeric seed (day-stable for quizzes) */
function seededPick<T>(arr: T[], n: number, seed: number): T[] {
  const idx = arr.map((_, i) => ({ i, k: Math.sin(seed * 9301 + i * 49297) * 233280 }));
  idx.sort((a, b) => a.k - b.k);
  return idx.slice(0, n).map((x) => arr[x.i]);
}

