export function offlineQuizScore(
  questions: { id: string; question: string; options: string[]; correctIndex: number; explanation?: string; topic?: string }[],
  answers: Record<string, unknown>,
): Record<string, unknown> | null {
  if (!Array.isArray(questions) || questions.length === 0) return null;
  let score = 0;
  const results = questions.map((q) => {
    const ua = Number(answers[q.id]);
    const isCorrect = Number.isFinite(ua) && ua === Number(q.correctIndex);
    if (isCorrect) score++;
    return {
      question: q.question,
      options: q.options,
      userAnswer: Number.isFinite(ua) ? ua : -1,
      correctAnswer: q.correctIndex,
      isCorrect,
      explanation: q.explanation || "",
      topic: q.topic || "General",
    };
  });
  const total = questions.length;
  const percentage = Math.round((score / total) * 100);
  let grade = "Needs improvement";
  if (percentage >= 90) grade = "Health expert!";
  else if (percentage >= 75) grade = "Health smart";
  else if (percentage >= 50) grade = "Getting there";
  return { score, total, percentage, grade, results, source: OFFLINE_SOURCE };
}

