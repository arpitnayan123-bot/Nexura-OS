export interface SymptomResult {
  summary: string;
  urgency: "low" | "moderate" | "high" | "emergency";
  possibleCauses: { condition: string; likelihood: "low" | "moderate" | "high"; note: string }[];
  recommendedActions: string[];
  redFlags: string[];
  specialty: string;
  disclaimer: string;
  source?: string;
}

export function offlineSymptomsChecker(symptoms: string): SymptomResult | null {
  const text = (symptoms || "").trim();
  if (text.length < 3) return null;
  const t = text.toLowerCase();

  for (const [re, label] of SYMPTOM_EMERGENCY_KEYWORDS) {
    if (re.test(t)) {
      return {
        summary: `You mentioned ${label}. This combination can be serious and should not wait — please seek emergency care now (nearest hospital emergency room, or call 108 in India). Do not drive yourself if you feel faint.`,
        urgency: "emergency",
        possibleCauses: [],
        recommendedActions: [
          "Go to the nearest emergency department immediately or call 108 (ambulance)",
          "Do not eat/drink anything if surgery may be needed",
          "If someone is with you, let them drive and carry your medicine list",
        ],
        redFlags: SYMPTOM_DEFAULT_REDACTIONS,
        specialty: "Emergency Medicine",
        disclaimer: OFFLINE_DISCLAIMER,
        source: OFFLINE_SOURCE,
      };
    }
  }

  const high = SYMPTOM_HIGH_KEYWORDS.filter(([re]) => re.test(t)).map(([, l]) => l);
  const matched = SYMPTOM_CAUSE_RULES.filter((r) => r.re.test(t));
  const causes = matched.slice(0, 4).map((r) => ({
    condition: r.condition,
    likelihood: r.likelihood,
    note: r.note,
  }));
  if (causes.length === 0) {
    causes.push(
      {
        condition: "Common self-limiting illness",
        likelihood: "moderate",
        note: "Your description does not match a specific pattern — most new, mild symptoms in this range settle in 48-72 hours.",
      },
      {
        condition: "Early stage of a longer illness",
        likelihood: "low",
        note: "Watch for new fever, spreading pain, or breathlessness over the next 1-2 days.",
      },
    );
  }

  const urgency: SymptomResult["urgency"] = high.length > 0 ? "high" : causes.length > 0 ? "low" : "low";
  const specialty = matched[0]?.specialty ?? "General Physician";
  const actions: string[] = [];
  for (const m of matched.slice(0, 3)) for (const a of m.actions ?? []) if (!actions.includes(a)) actions.push(a);
  if (actions.length === 0) {
    actions.push(
      "Rest, hydrate well (3+ litres of fluids daily) and monitor how you feel over 48 hours",
      "Note when the symptom started, what worsens/eases it — doctors find this very useful",
    );
  }
  if (actions.length < 5)
    actions.push("Book a " + specialty.split(" / ")[0] + " visit if symptoms persist beyond 48-72 hours");

  return {
    summary:
      high.length > 0
        ? `Based on your description (${high.join("; ")}), this deserves same-day medical attention. While it may still turn out to be minor, a doctor should examine you today to rule out anything serious.`
        : `Based on your description, the most likely explanations are ${causes
            .slice(0, 2)
            .map((c) => c.condition.toLowerCase())
            .join(" or ")}. Most such symptoms settle with basic care within a couple of days — but keep an eye on the red flags below.`,
    urgency,
    possibleCauses: causes,
    recommendedActions: actions.slice(0, 6),
    redFlags: SYMPTOM_DEFAULT_REDACTIONS,
    specialty,
    disclaimer: OFFLINE_DISCLAIMER,
    source: OFFLINE_SOURCE,
  };
}

/* ============================================================
   2. BLOOD PRESSURE ANALYZER (computed values passed in)
   ============================================================ */

export interface BpResult {
  classification: string;
  averageSystolic: number;
  averageDiastolic: number;
  pulsePressure: number;
  trend: "stable" | "increasing" | "decreasing" | "fluctuating";
  pattern: string;
  whiteCoatSuspected: boolean;
  targetRange: string;
  recommendations: string[];
  whenToSeeDoctor: string;
  disclaimer: string;
  source?: string;
}

export function offlineBp(
  rawReadings: { systolic?: number; diastolic?: number }[],
): BpResult | null {
  const clean = (Array.isArray(rawReadings) ? rawReadings : [])
    .filter(
      (r) =>
        r &&
        Number(r.systolic) > 50 &&
        Number(r.systolic) < 300 &&
        Number(r.diastolic) > 30 &&
        Number(r.diastolic) < 200,
    )
    .map((r) => ({ systolic: Number(r.systolic), diastolic: Number(r.diastolic) }));
  if (clean.length === 0) return null;
  const avgSys = clean.reduce((a, r) => a + r.systolic, 0) / clean.length;
  const avgDia = clean.reduce((a, r) => a + r.diastolic, 0) / clean.length;
  const pulse = avgSys - avgDia;
  const readings = clean;
  let classification: string;
  if (avgSys >= 180 || avgDia >= 120) classification = "Hypertensive Crisis";
  else if (avgSys >= 140 || avgDia >= 90) classification = "Stage 2 Hypertension";
  else if (avgSys >= 130 || avgDia >= 80) classification = "Stage 1 Hypertension";
  else if (avgSys >= 120) classification = "Elevated";
  else classification = "Normal";

  const sysVals = readings.map((r) => Number(r?.systolic)).filter((n) => Number.isFinite(n));
  let trend: BpResult["trend"] = "stable";
  if (sysVals.length >= 4) {
    const half = Math.floor(sysVals.length / 2);
    const first = sysVals.slice(0, half).reduce((a, b) => a + b, 0) / half;
    const last = sysVals.slice(-half).reduce((a, b) => a + b, 0) / half;
    const diff = last - first;
    if (diff > 8) trend = "increasing";
    else if (diff < -8) trend = "decreasing";
    else {
      const min = Math.min(...sysVals);
      const max = Math.max(...sysVals);
      if (max - min > 25) trend = "fluctuating";
    }
  }

  let whiteCoat = false;
  if (sysVals.length >= 3) {
    const rest = [...sysVals].slice(1);
    const restMedian = [...rest].sort((a, b) => a - b)[Math.floor(rest.length / 2)] ?? sysVals[0];
    whiteCoat = sysVals[0] - restMedian >= 15;
  }

  const pattern = whiteCoat
    ? "Your first reading was notably higher than the rest — a classic white-coat pattern (BP rises in clinical/stressful settings). Home readings taken calmly are usually the truer picture."
    : classification.startsWith("Stage") || classification === "Hypertensive Crisis"
      ? "Readings are consistently in this range across your log, suggesting a sustained pattern rather than a one-off spike."
      : "Readings are within an expected band across your log.";

  return {
    classification,
    averageSystolic: r0(avgSys),
    averageDiastolic: r0(avgDia),
    pulsePressure: r0(pulse),
    trend,
    pattern,
    whiteCoatSuspected: whiteCoat,
    targetRange:
      "Generally <130/80 mmHg for adults; <140/90 if over 60 or with multiple conditions (your doctor confirms your personal target)",
    recommendations: BP_RECOMMENDATIONS[classification] ?? BP_RECOMMENDATIONS.Elevated,
    whenToSeeDoctor: BP_DOCTOR_NOTE[classification] ?? BP_DOCTOR_NOTE.Elevated,
    disclaimer: OFFLINE_DISCLAIMER,
    source: OFFLINE_SOURCE,
  };
}

