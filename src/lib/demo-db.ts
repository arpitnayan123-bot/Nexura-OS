import { existsSync, copyFileSync } from "node:fs";
import path from "node:path";
import { log } from "@/lib/logger";

/* ============================================================
   NEXURA OS — SERVERLESS ZERO-CONFIG DEMO DATABASE (vercel-deploy-3)

   Problem this solves: Vercel projects wired to this repo with NO
   environment variables configured used to die at boot —
   assertProductionEnv() threw ("Refusing to boot") and every route
   returned 500. That turned "not configured yet" into a blank wall
   of errors, which is the worst possible first-run experience for
   a portfolio/demo deployment.

   Solution: the repo ships a SEEDED SQLite demo database as a build
   artifact (db/demo.db, built by scripts/build-prisma.mjs +
   scripts/build-demo-db.mjs; the Prisma client is generated for the
   sqlite provider by the same selector that runs in `bun run build`).
   On a serverless runtime with no DATABASE_URL, this module:

     1. locates the bundled db/demo.db (node-file-trace copies it
        into every function bundle via next.config's
        outputFileTracingIncludes),
     2. copies it to /tmp (the only writable directory on Vercel),
     3. points DATABASE_URL at the writable copy, and
     4. defaults DEMO_MODE=true unless explicitly set to "false".

   Semantics of the resulting deployment:
   - Fully working demo: seeded hospitals, staff logins, pharmacy,
     clinic, portal — exactly the sandbox demo experience.
   - Per-instance and ephemeral: each serverless instance gets its
     own /tmp copy; writes never outlive the instance. That is the
     documented trade-off of a zero-config demo.
   - Explicitly-configurable away: as soon as DATABASE_URL is set
     (any hosted Postgres — Neon/Supabase/Vercel Postgres), this
     module is a no-op and the deployment uses the real database.
     DEMO_MODE=false disables the demo surfaces even without a DB.

   Must run BEFORE any PrismaClient is constructed — wired from
   src/instrumentation.ts register(), which Next.js executes before
   serving requests in production.
   ============================================================ */

const DEMO_DB_FILENAME = "demo.db";
const RUNTIME_DB_PATH = "/tmp/nexura-demo.db";

/** True when the process is a serverless/PaaS runtime this module manages. */
export function isServerlessRuntime(): boolean {
  return process.env.VERCEL === "1" || process.env.NEXURA_DEMO_DB === "1";
}

/**
 * Locate the demo database bundled into this function. node-file-trace
 * preserves project-root-relative paths, but the process cwd differs
 * between runtimes (Vercel lambda sandbox vs standalone server), so a
 * small candidate list is probed. NEXURA_DEMO_DB_PATH wins if set.
 */
export function resolveBundledDemoDb(): string | null {
  const override = process.env.NEXURA_DEMO_DB_PATH;
  if (override) return existsSync(override) ? override : null;
  const cwd = process.cwd();
  const candidates = [
    path.join(cwd, "db", DEMO_DB_FILENAME),
    path.join(cwd, "..", "db", DEMO_DB_FILENAME),
    path.join(cwd, "..", "..", "db", DEMO_DB_FILENAME),
  ];
  for (const p of candidates) {
    try {
      if (existsSync(p)) return p;
    } catch {
      // unreadable candidate — try the next one
    }
  }
  return null;
}

/**
 * Attach the embedded demo database when the runtime has no real
 * DATABASE_URL. Returns true when the demo DB was attached.
 */
export function ensureServerlessDemoDatabase(): boolean {
  if (!isServerlessRuntime()) return false;
  if (process.env.DATABASE_URL) return false; // real database attached — nothing to do

  const bundled = resolveBundledDemoDb();
  if (!bundled) {
    log.error(
      "demo-db",
      "No DATABASE_URL and no bundled demo database (db/demo.db) found — " +
        "this deployment will run WITHOUT a data layer: data-backed routes will fail. " +
        "Set DATABASE_URL (any hosted Postgres) to fix, or rebuild with db/demo.db present.",
    );
    return false;
  }

  try {
    copyFileSync(bundled, RUNTIME_DB_PATH);
  } catch (err) {
    log.error(
      "demo-db",
      `Failed to materialize the demo database at ${RUNTIME_DB_PATH}: ${
        err instanceof Error ? err.message : String(err)
      } — continuing without a data layer.`,
    );
    return false;
  }

  process.env.DATABASE_URL = `file:${RUNTIME_DB_PATH}`;
  /* Legacy alias: demo-schema clients generated by older build-prisma
     versions pointed the datasource at DEMO_DB_URL. Harmless for current
     clients (they read DATABASE_URL) and keeps mixed build caches working. */
  process.env.DEMO_DB_URL = `file:${RUNTIME_DB_PATH}`;
  // Zero-config = zero real users/data: this deployment is a demo by
  // construction. An explicit DEMO_MODE=false is always respected.
  if (!process.env.DEMO_MODE) process.env.DEMO_MODE = "true";

  log.warn(
    "demo-db",
    "Zero-config serverless demo posture: no DATABASE_URL was configured, so the " +
      "embedded seeded demo database was attached (per-instance, ephemeral writes, " +
      "synthetic data, DEMO_MODE=true). Set DATABASE_URL (Neon/Supabase/Vercel Postgres) " +
      "and redeploy for a persistent, production-capable deployment.",
  );
  return true;
}
