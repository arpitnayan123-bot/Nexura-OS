const RUNNERS: Record<NxTrigger, (ctx: AutomationCtx) => Promise<StepLog[]>> = {
  "result.critical": runCriticalResult,
  "discharge.confirmed": runDischargeConfirmed,
  "bed.ready": runBedReady,
  "order.created": runOrderCreated,
  "appointment.created": runAppointmentCreated,
};

/** Fire every enabled rule bound to this trigger. Never throws.
 *  Also fans out to (a) webhook subscribers and (b) escalation policies —
 *  integrations and safety nets ride the same deterministic trigger path. */
export async function fire(trigger: NxTrigger, ctx: AutomationCtx): Promise<void> {
  try {
    dispatchWebhooks(ctx.hospitalId, trigger as WebhookEvent, {
      patientId: ctx.patientId,
      patientUhid: ctx.patientUhid,
      patientName: ctx.patientName,
      relatedId: ctx.relatedId,
    });
    void evaluateEscalation(ctx.hospitalId, trigger as WebhookEvent, ctx.relatedId || "");
    const rules = await db.nxAutomationRule.findMany({
      where: { hospitalId: ctx.hospitalId, triggerType: trigger, enabled: true },
    });
    const runner = RUNNERS[trigger];
    for (const rule of rules) {
      const startedAt = new Date();
      let steps: StepLog[] = [];
      let status = "completed";
      try {
        steps = await runner(ctx);
      } catch (err) {
        status = "failed";
        steps = [{ name: "Execution", status: "skipped", detail: String(err), at: nowISO() }];
      }
      await db.nxWorkflowRun.create({
        data: {
          hospitalId: ctx.hospitalId,
          ruleId: rule.id,
          ruleName: rule.name,
          patientId: ctx.patientId,
          patientUhid: ctx.patientUhid,
          status,
          currentStep: steps[steps.length - 1]?.name,
          steps: JSON.stringify(steps),
          startedAt,
          completedAt: new Date(),
        },
      });
      await db.nxAutomationRule.update({
        where: { id: rule.id },
        data: { lastRunAt: new Date(), runCount: { increment: 1 } },
      });
      await audit({
        hospitalId: ctx.hospitalId,
        actorName: "Nexura Automation",
        actorRole: "system",
        action: `automation.${trigger}`,
        entityType: "automation_run",
        entityId: rule.id,
        patientId: ctx.patientId,
        detail: { rule: rule.name, status, steps: steps.length },
      });
    }
  } catch (err) {
    console.error(`[nx-automations] trigger ${trigger} failed`, err);
  }
}
